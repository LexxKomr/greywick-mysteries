import type { SpiderMove } from './spider';

function decode(path: string): SpiderMove[] {
  return path.trim().split(' ').map((move) => {
    if (move === 'D') return { type: 'draw' };
    const [from, at, to] = [...move].map((digit) => parseInt(digit, 36));
    return { type: 'move', from, at, to };
  });
}

